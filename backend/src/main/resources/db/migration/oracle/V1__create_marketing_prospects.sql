CREATE SEQUENCE MKT_PROSPECT_SEQ
    START WITH 1
    INCREMENT BY 1
    MINVALUE 1
    NOCACHE
    NOCYCLE;

CREATE TABLE MKT_PROSPECT (
    ID NUMBER(19) NOT NULL,
    REQUEST_TYPE VARCHAR2(30 CHAR) NOT NULL,
    STATUS VARCHAR2(30 CHAR) DEFAULT 'NEW' NOT NULL,
    FIRST_NAME VARCHAR2(80 CHAR) NOT NULL,
    LAST_NAME VARCHAR2(100 CHAR),
    EMAIL VARCHAR2(180 CHAR) NOT NULL,
    PHONE VARCHAR2(40 CHAR),
    COMPANY VARCHAR2(160 CHAR) NOT NULL,
    JOB_TITLE VARCHAR2(140 CHAR),
    COMPANY_SIZE VARCHAR2(60 CHAR),
    TEAM_SIZE VARCHAR2(60 CHAR),
    STUDENT_COUNT NUMBER(10),
    SERVICE_INTEREST VARCHAR2(140 CHAR),
    TECHNOLOGY_INTEREST VARCHAR2(300 CHAR),
    PLAN_ID VARCHAR2(100 CHAR),
    MESSAGE VARCHAR2(2000 CHAR) NOT NULL,
    SOURCE VARCHAR2(160 CHAR),
    CONSENT_PRIVACY NUMBER(1) DEFAULT 1 NOT NULL,
    CONSENT_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    IP_HASH VARCHAR2(64 CHAR),
    USER_AGENT VARCHAR2(500 CHAR),
    CONTENT_FINGERPRINT VARCHAR2(64 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_MKT_PROSPECT PRIMARY KEY (ID),
    CONSTRAINT CK_MKT_PROSPECT_CONSENT CHECK (CONSENT_PRIVACY IN (0, 1)),
    CONSTRAINT CK_MKT_PROSPECT_STUDENTS CHECK (STUDENT_COUNT IS NULL OR STUDENT_COUNT > 0)
);

CREATE INDEX IX_MKT_PROSPECT_EMAIL ON MKT_PROSPECT (EMAIL);
CREATE INDEX IX_MKT_PROSPECT_STATUS_CREATED ON MKT_PROSPECT (STATUS, CREATED_AT);
CREATE INDEX IX_MKT_PROSPECT_TYPE_CREATED ON MKT_PROSPECT (REQUEST_TYPE, CREATED_AT);
CREATE INDEX IX_MKT_PROSPECT_FINGERPRINT ON MKT_PROSPECT (CONTENT_FINGERPRINT, CREATED_AT);
